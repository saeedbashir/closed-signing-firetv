#!/usr/bin/env node
/**
 * Regenerate `app/src/catalogue.ts` from published STM manifests.
 *
 * `catalogue.ts` carries a comment saying not to hand-edit it and to regenerate
 * instead — but the thing that regenerates it was never committed, so the only
 * way to change a title was to do the forbidden thing. This is that script.
 *
 * Usage:
 *   node tools/build-catalogue.mjs <manifest-url> [<manifest-url> ...]
 *
 * Reads each manifest over HTTPS, so what ships in the app is what is actually
 * published — a catalogue that disagrees with the bucket is worse than no
 * catalogue, because it fails at play time rather than at build time.
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'app', 'src', 'catalogue.ts');

const HEADER = `/**
 * The catalogue the app ships with.
 *
 * Bundled rather than fetched: the hackathon rules require the repository to
 * contain everything needed for the project to be functional, and a judge
 * should not need an account to press play. The media itself is served over
 * HTTPS, because Vega's media player refuses plain HTTP and cannot read a
 * local file path from inside the app sandbox — measured, see friction-log/003.
 *
 * Generated by tools/build-catalogue.mjs from published manifests. Do not
 * hand-edit; re-run that script.
 */
import type { Catalogue, TitleManifest } from './stm/types';

`;

const urls = process.argv.slice(2);
if (urls.length === 0) {
  console.error('usage: build-catalogue.mjs <manifest-url> [...]');
  process.exit(2);
}

const manifests = [];
for (const url of urls) {
  const response = await fetch(url);
  if (!response.ok) {
    console.error(`${url}: HTTP ${response.status}`);
    process.exit(1);
  }
  const manifest = await response.json();
  if (manifest.stmVersion !== '0.1') {
    console.error(`${url}: unexpected stmVersion ${manifest.stmVersion}`);
    process.exit(1);
  }
  manifests.push(manifest);
  const signed = (manifest.signLanguage ?? []).length;
  const captions = (manifest.captions ?? []).length;
  console.log(`${manifest.id}: ${signed} sign track(s), ${captions} caption track(s)`);
}

const catalogue = {
  stmVersion: '0.1',
  titles: manifests.map((m) => ({
    id: m.id,
    title: m.title,
    durationMs: m.durationMs,
    poster: m.video.poster,
    manifestUrl: 'bundled',
    signLanguages: (m.signLanguage ?? []).map((t) => t.language),
    ...(m.signLanguage?.[0]?.confidence !== undefined
      ? { confidence: m.signLanguage[0].confidence }
      : {}),
  })),
};

const byId = Object.fromEntries(manifests.map((m) => [m.id, m]));

writeFileSync(
  OUT,
  HEADER +
    `export const BUNDLED_CATALOGUE: Catalogue = ${JSON.stringify(catalogue, null, 2)};\n\n` +
    `export const BUNDLED_MANIFESTS: Record<string, TitleManifest> = ${JSON.stringify(byId, null, 2)};\n`,
);
console.log(`wrote ${OUT}`);
